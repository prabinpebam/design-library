#!/usr/bin/env node
/**
 * Template tokens (Q64): each template's own component tokens, `packages/templates/{template}/tokens/tokens.json`
 * (W3C DTCG), become `tokens.css` in the same folder as custom properties in `@layer templates`. Every token must be
 * named `t.{template}.{part}.{name}`, carry a `$description`, and alias a core **semantic** token (`{space.stack-item}`),
 * never a primitive (`p.*`), a core component's token (`c.*`) or a raw value, so a template's parts follow the theme,
 * every context and every core change. An alias stays live: `--t-…: var(--space-stack-item)`.
 *
 *   node tools/template-tokens.mjs           write every template's tokens.css
 *   node tools/template-tokens.mjs --check   fail if a token breaks a rule or a tokens.css is stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const coreTokens = new Set(Object.keys(JSON.parse(readFileSync(join(root, 'packages/core/tokens/generated/tokens.resolved.json'), 'utf8')).light));
const dir = join(root, 'packages/templates');
const errors = [];
let written = 0;

for (const template of readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name)) {
  const source = join(dir, template, 'tokens', 'tokens.json');
  if (!existsSync(source)) continue;
  const rel = relative(root, source).split('\\').join('/');
  const tokens = [];
  const walk = (node, path) => {
    if (node && typeof node === 'object' && '$value' in node) return tokens.push({ path: path.join('.'), node });
    for (const [k, v] of Object.entries(node ?? {})) if (!k.startsWith('$')) walk(v, [...path, k]);
  };
  walk(JSON.parse(readFileSync(source, 'utf8')), []);
  const lines = [];
  for (const { path, node } of tokens) {
    if (!path.startsWith(`t.${template}.`)) errors.push(`${rel} · ${path} · isn't named t.${template}.{part}.{name}`);
    if (!node.$description) errors.push(`${rel} · ${path} · has no $description`);
    const alias = typeof node.$value === 'string' ? /^\{([a-z0-9.-]+)\}$/.exec(node.$value)?.[1] : undefined;
    if (!alias) {
      errors.push(`${rel} · ${path} · is a raw value (${JSON.stringify(node.$value)}); alias a core semantic token like {space.stack-item}`);
      continue;
    }
    if (/^(p|c|spectrum|set)\./.test(alias)) errors.push(`${rel} · ${path} · aliases ${alias}; template tokens alias semantic roles only`);
    else if (!coreTokens.has(alias)) errors.push(`${rel} · ${path} · aliases ${alias}, which isn't a core token`);
    lines.push(`    --${path.replaceAll('.', '-')}: var(--${alias.replaceAll('.', '-')});`);
  }
  const css = `/* Generated by tools/template-tokens.mjs from ${template}/tokens/tokens.json: do not edit. */\n@layer templates {\n  :root {\n${lines.join('\n')}\n  }\n}\n`;
  const target = join(dir, template, 'tokens', 'tokens.css');
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== css) errors.push(`${relative(root, target).split('\\').join('/')} · is stale · run npm run tokens`);
  } else {
    writeFileSync(target, css);
    written += 1;
  }
}

if (errors.length) {
  console.error(`template-tokens: ${errors.length} problem${errors.length === 1 ? '' : 's'}\n${errors.map((e) => `  ${e}`).join('\n')}`);
  process.exit(1);
}
console.log(check ? 'template-tokens: every template token aliases a core semantic role; tokens.css current.' : `template-tokens: wrote ${written} tokens.css.`);
