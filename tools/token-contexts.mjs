#!/usr/bin/env node
// @ts-check
/**
 * Context echoes (packet 3, 2026-11-07): makes aliases follow a modifier context inside a subtree.
 *
 * A custom property's var() is resolved on the element that declares it. Aliases such as
 * `--c-pane-border: var(--color-border)` are declared on :root, so a subtree that switches context
 * (`[data-contrast='more']` on a ContextMatrix cell or an Example preview) re-declares `--color-border` but still
 * inherits the alias computed from the page's context. This tool finds every token that aliases, directly or through
 * other aliases, a token a modifier context overrides, and writes those aliases again (same values) into
 * `tokens.<modifier>-echo.json`, which the resolver adds to each of that modifier's contexts. The build then
 * re-declares them in the context's selector, so they resolve against the subtree's values.
 *
 *   node tools/token-contexts.mjs           write the echo files
 *   node tools/token-contexts.mjs --check   fail (exit 1) when an echo file is stale, or a dependent can't be echoed
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { load } from '../agentic-craft/tools/build-tokens.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'packages/core/tokens');
const ALIAS = /^\{([^}]+)\}$/;
const echoFile = (/** @type {string} */ modifier) => `tokens.${modifier}-echo.json`;

/** The echo trees by modifier, and any dependent that can't be echoed. */
export function echoes() {
  const resolver = JSON.parse(readFileSync(join(SRC, 'resolver.json'), 'utf8'));
  /** @type {Record<string, { files: string[] }>} */
  const contexts = resolver.modifiers;
  const model = load(SRC);
  const theme = model.modifiers.theme?.contexts ?? {};
  const out = /** @type {Record<string, any>} */ ({});
  /** @type {string[]} */
  const problems = [];
  for (const [name, mod] of Object.entries(model.modifiers)) {
    if (name === 'theme') continue;
    const file = echoFile(name);
    // Tokens a context of this modifier overrides, from its own files (not from the echo file itself).
    const over = new Set();
    for (const [ctx, files] of Object.entries(contexts[name].contexts)) {
      void ctx;
      for (const f of /** @type {string[]} */ (files).filter((x) => x !== file)) {
        const walk = (/** @type {any} */ g, /** @type {string[]} */ p) => {
          for (const [k, v] of Object.entries(g)) if (!k.startsWith('$') && v && typeof v === 'object') ('$value' in v ? over.add([...p, k].join('.')) : walk(v, [...p, k]));
        };
        walk(JSON.parse(readFileSync(join(SRC, f), 'utf8')), []);
      }
    }
    void mod;
    const scopes = [model.base, theme.light ?? new Map(), theme.dark ?? new Map()];
    /** @type {Map<string, { value: string, type: string, owner?: string, description: string }>} */
    const deps = new Map();
    for (let grew = true; grew; ) {
      grew = false;
      for (const scope of scopes)
        for (const [path, t] of scope) {
          if (over.has(path) || deps.has(path)) continue;
          const a = typeof t.value === 'string' && ALIAS.exec(t.value);
          if (!a || !(over.has(a[1]) || deps.has(a[1]))) continue;
          const values = new Set(scopes.filter((s) => s.has(path)).map((s) => JSON.stringify(s.get(path)?.value)));
          if (values.size > 1) {
            problems.push(`${path} aliases ${a[1]} (overridden by ${name}) but differs between light and dark, so it can't be echoed; alias it the same way in both`);
            continue;
          }
          deps.set(path, { value: t.value, type: t.type, owner: t.owner, description: t.description });
          grew = true;
        }
    }
    const tree = /** @type {any} */ ({ $comment: `Generated by tools/token-contexts.mjs: aliases that read a token the ${name} modifier overrides, declared again in each ${name} context so they follow a subtree's context. Never edit by hand.` });
    for (const [path, t] of [...deps].sort(([a], [b]) => a.localeCompare(b))) {
      const parts = path.split('.');
      let node = tree;
      for (const [i, key] of parts.slice(0, -1).entries()) {
        node = node[key] ??= {};
        if (i === 1 && parts[0] === 'c' && t.owner) node.$extensions = { owner: t.owner };
      }
      node[parts.at(-1)] = { $type: t.type, $value: t.value, $description: `${t.description} (echoed for ${name} contexts)` };
    }
    out[name] = tree;
  }
  return { out, problems };
}

function main(/** @type {string[]} */ argv) {
  const { out, problems } = echoes();
  const stale = [];
  for (const [name, tree] of Object.entries(out)) {
    const file = join(SRC, echoFile(name));
    const text = JSON.stringify(tree, null, 2) + '\n';
    if (argv.includes('--check')) {
      if (!existsSync(file) || readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text) stale.push(`${relative(ROOT, file)} is stale: run npm run tokens`);
    } else writeFileSync(file, text);
  }
  for (const p of [...problems, ...stale]) console.error(`✗ ${p}`);
  if (!problems.length && !stale.length) console.log(`token contexts: ${Object.entries(out).map(([n, t]) => `${n} ${JSON.stringify(t).match(/"\$value"/g)?.length ?? 0} echoed`).join(', ')}`);
  return problems.length || stale.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
