#!/usr/bin/env node
/**
 * `npm run content:schemas` (Q64): writes each application template's content.schema.json from the record types in
 * its own `types.ts`, so the schema and the types its registry reads can't drift. Each record becomes
 * `$defs/record.{layout}` (or `record.shared` for the shared file); the envelope stays the core one.
 * Uses ts-json-schema-generator through npx (the approved npm proxy in .npmrc).
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
/** Template → { record name → the type in its types.ts }. */
const records = {
  chat: { chat: 'ChatAppView' },
  design: { editor: 'DesignAppSpec' },
  projects: { shared: 'ProjectRecord', issue: 'IssueDetail' },
};

const tmp = mkdtempSync(join(tmpdir(), 'content-schemas-'));
try {
  for (const [template, map] of Object.entries(records)) {
    const manifest = JSON.parse(readFileSync(join(root, 'packages/templates', template, 'template.json'), 'utf8'));
    const defs = {};
    for (const [record, type] of Object.entries(map)) {
      const out = join(tmp, `${template}-${record}.json`);
      execFileSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['-y', 'ts-json-schema-generator@2', '--path', `packages/templates/${template}/types.ts`, '--type', type, '--tsconfig', 'apps/library/tsconfig.json', '--no-type-check', '-o', out], { cwd: root, stdio: 'inherit', shell: process.platform === 'win32' });
      const generated = JSON.parse(readFileSync(out, 'utf8').replaceAll('#/definitions/', '#/$defs/'));
      Object.assign(defs, generated.definitions);
      defs[`record.${record}`] = { $ref: `#/$defs/${type}` };
    }
    const schema = {
      $schema: 'https://json-schema.org/draft/2020-12/schema',
      $id: `https://design-library.local/templates/${template}/content/${manifest.contentVersion}`,
      title: `${manifest.title} content, version ${manifest.contentVersion}`,
      description: `Generated by npm run content:schemas from packages/templates/${template}/types.ts: do not edit by hand. The core envelope; each file's record is $defs/record.{layout} (record.shared for the shared file).`,
      $ref: 'https://design-library.local/core/content/1',
      $defs: Object.fromEntries(Object.entries(defs).sort(([a], [b]) => a.localeCompare(b))),
    };
    writeFileSync(join(root, 'packages/templates', template, 'content.schema.json'), JSON.stringify(schema, null, 2) + '\n');
    console.log(`${template}: ${Object.keys(map).map((r) => `record.${r}`).join(', ')}`);
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
