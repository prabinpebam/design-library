// Subsets the MIT-licensed flag-icons set (https://github.com/lipis/flag-icons, licence verified 2026-11-07) into
// packages/core/flags/flags.ts: only the countries the library lists, as 4:3 SVG markup keyed by ISO 3166-1 alpha-2.
// Usage: node ./tools/flags.mjs          writes the module
//        node ./tools/flags.mjs --check  fails when the module is out of date
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const countries = ['in', 'us', 'gb', 'de', 'jp', 'fr', 'br', 'au', 'ca', 'cn'];
const src = join(root, 'node_modules', 'flag-icons');
const out = join(root, 'packages', 'core', 'flags', 'flags.ts');

const version = JSON.parse(readFileSync(join(src, 'package.json'), 'utf8')).version;
const entries = countries.map((c) => {
  const svg = readFileSync(join(src, 'flags', '4x3', `${c}.svg`), 'utf8').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
  return `  ${c}: ${JSON.stringify(svg)},`;
});
const text = `// Generated by tools/flags.mjs from flag-icons ${version} (MIT, (c) 2013 Panayiotis Lipiridis,
// https://github.com/lipis/flag-icons). Do not edit; add a country to the tool's list and rerun it.
export const flags = {
${entries.join('\n')}
} as const;

export type FlagCode = keyof typeof flags;
`;

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    console.error('flags: packages/core/flags/flags.ts is out of date; run node ./tools/flags.mjs');
    process.exit(1);
  }
  console.log(`flags: ${countries.length} flags up to date (flag-icons ${version})`);
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`flags: wrote ${countries.length} flags from flag-icons ${version}`);
}
