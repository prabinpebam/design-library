#!/usr/bin/env node
// State coverage (F13, D9; contract L3): which UI states each core component can be in, read from its props in the
// agent index, and which of those its stories show. Writes tools/state-coverage.json; `--check` fails when the file is
// stale or when a component that showed an applicable state no longer does (a ratchet: gaps are listed, and close
// one story at a time).
//
//   node tools/state-coverage.mjs [--check]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const agent = join(root, 'packages/core/agent/components');
const out = join(root, 'tools/state-coverage.json');
// A state applies when a prop names it; a story shows it when the stories file sets that prop (or, for empty, shows an
// empty list or EmptyState).
const STATES = {
  disabled: { prop: /^(disabled|unavailable)$/, story: /\b(disabled|unavailable)(\s*=\s*\{?\s*true\}?|[\s/>])/ },
  loading: { prop: /^(loading|busy|pending)$/, story: /\b(loading|busy|pending)(\s*=\s*\{?\s*true\}?|[\s/>])/ },
  error: { prop: /^(error|invalid|errors)$/, story: /\b(error|invalid|errors)\s*=\s*[{"']/ },
  empty: { prop: /^(empty|emptyState|emptyLabel|emptyMessage)$/, story: /\b(empty|emptyState|emptyLabel|emptyMessage)\s*=|<EmptyState\b|items=\{\[\]\}|rows=\{\[\]\}/ },
};
const storiesFor = (file) => {
  const f = join(root, 'packages/core/react/stories', file.split('/').pop().replace(/\.tsx$/, '.stories.tsx'));
  return existsSync(f) ? readFileSync(f, 'utf8') : '';
};
const rows = {};
for (const name of readdirSync(agent).filter((n) => n.endsWith('.json') && !/^[a-z]+\./.test(n)).sort()) {
  const c = JSON.parse(readFileSync(join(agent, name), 'utf8'));
  if (!c.file) continue;
  const props = (c.props ?? []).flatMap((i) => (i.props ?? []).map((p) => p.name));
  const stories = storiesFor(c.file);
  const row = {};
  for (const [state, { prop, story }] of Object.entries(STATES)) if (props.some((p) => prop.test(p))) row[state] = story.test(stories);
  if (Object.keys(row).length) rows[c.name] = row;
}
const applicable = Object.values(rows).reduce((n, r) => n + Object.keys(r).length, 0);
const shown = Object.values(rows).reduce((n, r) => n + Object.values(r).filter(Boolean).length, 0);
const per = Object.fromEntries(Object.keys(STATES).map((s) => [s, `${Object.values(rows).filter((r) => r[s]).length}/${Object.values(rows).filter((r) => s in r).length}`]));
const doc = { $description: 'Generated by tools/state-coverage.mjs: per core component, the UI states its props allow and whether its stories show each (true) or not (false). Contract L3, scorecard D9.', summary: { components: Object.keys(rows).length, applicable, shown, perState: per }, components: rows };
const text = JSON.stringify(doc, null, 2) + '\n';
if (process.argv.includes('--check')) {
  if (!existsSync(out)) (console.error('state-coverage: tools/state-coverage.json is missing; run node tools/state-coverage.mjs'), process.exit(1));
  const was = JSON.parse(readFileSync(out, 'utf8')).components ?? {};
  const lost = Object.entries(was).flatMap(([n, r]) => Object.entries(r).filter(([s, v]) => v && rows[n]?.[s] === false).map(([s]) => `${n} ${s}`));
  if (lost.length) (console.error(`state-coverage: stories no longer show ${lost.join(', ')}`), process.exit(1));
  if (readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== text) (console.error('state-coverage: tools/state-coverage.json is stale; run node tools/state-coverage.mjs'), process.exit(1));
  console.log(`state-coverage: ${shown} of ${applicable} applicable states shown in stories (${Object.entries(per).map(([s, v]) => `${s} ${v}`).join(', ')}); current.`);
} else {
  writeFileSync(out, text);
  console.log(`state-coverage: wrote tools/state-coverage.json, ${shown} of ${applicable} applicable states shown (${Object.entries(per).map(([s, v]) => `${s} ${v}`).join(', ')}).`);
}
