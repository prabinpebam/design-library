#!/usr/bin/env node
// @ts-check
/**
 * Space and shape build and check (owner F12, 2026-11-07; docs/foundation.md#space-and-shape-options). Dependency-free.
 *
 *   node tools/space-shape.mjs           space-shape.config.json + space-shape-options.json →
 *                                        tokens.space-shape.json (the theme's roles, in the base set) and one file per
 *                                        option (tokens.space-<option>.json, tokens.shape-<option>.json), which the
 *                                        resolver turns into [data-space] and [data-shape] contexts
 *   node tools/space-shape.mjs --check   fails (exit 1) on: an invalid config or option table, stale output, or a
 *                                        broken invariant in any option (below)
 *
 * Invariants, in every option: each space role reads a step of the 4 px scale; a pair is never wider than an item;
 * groups sit at least 1.5 times the item space apart and sections at least twice the group space; inside an enclosure
 * no gap exceeds its inset; insets grow sm ≤ md ≤ lg. Sharp is 0 everywhere; radii grow sm ≤ md ≤ lg; radius.none and
 * radius.full (round by nature) never change and only the allow-listed round-by-nature parts read radius.full. Sizes
 * and targets aren't roles, so no option can touch them.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'packages/core/tokens');
const CONFIG = join(SRC, 'space-shape.config.json');
const OPTIONS = join(SRC, 'space-shape-options.json');
const BASE_OUT = 'tokens.space-shape.json';
const VERSION = 'space-shape-config/1';
/** Tokens allowed to read radius.full: shapes round by nature, which stay round when the theme is sharp. */
const ROUND_BY_NATURE = new Set(['c.token-specimen.track-radius']);

const serialise = (/** @type {any} */ tree) => JSON.stringify(tree, null, 2) + '\n';
const read = (/** @type {string} */ file) => JSON.parse(readFileSync(file, 'utf8'));

/** A radius literal ("0.25rem", "999px", "0rem") as a DTCG dimension. */
function dimension(/** @type {string} */ text) {
  const m = /^(\d+(?:\.\d+)?)(rem|px)$/.exec(text);
  if (!m) throw new Error(`"${text}" isn't a dimension in rem or px`);
  return { value: Number(m[1]), unit: m[2] };
}
const px = (/** @type {{ value: number, unit: string }} */ d) => (d.unit === 'rem' ? d.value * 16 : d.value);

/** The token trees: the theme's roles for the base set, and one tree per option. */
export function generate(/** @type {any} */ config, /** @type {any} */ options) {
  const spaceTree = (/** @type {string} */ option, /** @type {string} */ note) => {
    const o = options.space.options[option];
    return Object.fromEntries(Object.entries(options.space.roles).map(([role, description]) => [role, { $type: 'dimension', $value: `{${o.values[role]}}`, $description: `${description}${note}` }]));
  };
  const shapeTree = (/** @type {string} */ option, /** @type {string} */ note) => {
    const o = options.shape.options[option];
    return Object.fromEntries(Object.entries(options.shape.roles).map(([role, description]) => [role, { $type: 'dimension', $value: dimension(o.values[role]), $description: `${description}${note}` }]));
  };
  /** @type {Record<string, any>} */
  const files = {
    [BASE_OUT]: {
      $comment: `Generated by tools/space-shape.mjs from space-shape.config.json (space: ${config.space}, shape: ${config.shape}). The theme's space and radius roles. Never edit by hand.`,
      space: spaceTree(config.space, ''),
      radius: shapeTree(config.shape, ''),
    },
  };
  for (const option of Object.keys(options.space.options))
    files[`tokens.space-${option}.json`] = { $comment: `Generated by tools/space-shape.mjs: the space roles in the ${option} option, for [data-space='${option}']. Never edit by hand.`, space: spaceTree(option, ` (${options.space.options[option].label.toLowerCase()} space)`) };
  for (const option of Object.keys(options.shape.options))
    files[`tokens.shape-${option}.json`] = { $comment: `Generated by tools/space-shape.mjs: the radius roles in the ${option} option, for [data-shape='${option}']. Never edit by hand.`, radius: shapeTree(option, ` (${options.shape.options[option].label.toLowerCase()} shape)`) };
  return files;
}

/** Everything wrong with the config, the option tables and the tokens that read them. */
export function problems(/** @type {any} */ config, /** @type {any} */ options, /** @type {any} */ authored) {
  const out = [];
  if (config.version !== VERSION) out.push(`space-shape.config.json: version must be "${VERSION}"`);
  for (const k of Object.keys(config)) if (!['$schema', 'version', 'space', 'shape'].includes(k)) out.push(`space-shape.config.json: unknown key "${k}"`);
  if (!options.space.options[config.space]) out.push(`space-shape.config.json: space "${config.space}" isn't an option (${Object.keys(options.space.options).join(', ')})`);
  if (!options.shape.options[config.shape]) out.push(`space-shape.config.json: shape "${config.shape}" isn't an option (${Object.keys(options.shape.options).join(', ')})`);

  const scale = Object.fromEntries(Object.entries(authored.space).filter(([, t]) => t && typeof t === 'object' && '$value' in t && typeof t.$value === 'object').map(([k, t]) => [`space.${k}`, px(/** @type {any} */ (t).$value)]));
  for (const [name, o] of Object.entries(/** @type {Record<string, any>} */ (options.space.options))) {
    const roles = Object.keys(options.space.roles);
    const missing = roles.filter((r) => !(r in o.values));
    const extra = Object.keys(o.values).filter((r) => !roles.includes(r));
    if (missing.length || extra.length) out.push(`space ${name}: roles must be exactly the space roles (missing ${missing.join(', ') || 'none'}, extra ${extra.join(', ') || 'none'})`);
    const v = /** @type {Record<string, number>} */ ({});
    for (const r of roles) {
      if (!(o.values[r] in scale)) out.push(`space ${name}: ${r} reads "${o.values[r]}", not a step of the scale`);
      v[r] = scale[o.values[r]] ?? NaN;
    }
    const hold = (/** @type {boolean} */ ok, /** @type {string} */ what) => ok || out.push(`space ${name}: ${what}`);
    hold(v['stack-pair'] <= v['stack-item'], 'a stacked pair is wider than an item');
    hold(v['inline-pair'] <= v['inline-item'], 'an inline pair is wider than an item');
    hold(v['stack-row'] <= v['stack-item'], 'filled rows sit further apart than items');
    hold(v['stack-group'] >= 1.5 * v['stack-item'], 'groups sit less than 1.5 times the item space apart');
    hold(v['inline-group'] >= 1.5 * v['inline-item'], 'inline groups sit less than 1.5 times the item space apart');
    hold(v['stack-section'] >= 2 * v['stack-group'], 'sections sit less than twice the group space apart');
    hold(v['stack-item'] <= v['inset-sm'] && v['inline-item'] <= v['inset-sm'], 'items inside a compact container sit further apart than its inset');
    hold(v['stack-group'] <= v['inset-md'], 'groups inside a card sit further apart than its inset');
    hold(v['inset-xs'] <= v['inset-sm'] && v['inset-sm'] <= v['inset-md'] && v['inset-md'] <= v['inset-lg'], 'insets must grow xs ≤ sm ≤ md ≤ lg');
  }
  for (const [name, o] of Object.entries(/** @type {Record<string, any>} */ (options.shape.options))) {
    const roles = Object.keys(options.shape.roles);
    if (roles.some((r) => !(r in o.values)) || Object.keys(o.values).some((r) => !roles.includes(r))) out.push(`shape ${name}: roles must be exactly the radius roles`);
    try {
      const v = Object.fromEntries(roles.map((r) => [r, px(dimension(o.values[r]))]));
      if (name === 'sharp' && roles.some((r) => v[r] !== 0)) out.push('shape sharp: every role must be 0');
      if (!(v.sm <= v.md && v.md <= v.lg)) out.push(`shape ${name}: radii must grow sm ≤ md ≤ lg`);
    } catch (e) {
      out.push(`shape ${name}: ${/** @type {Error} */ (e).message}`);
    }
  }
  for (const fixed of ['none', 'full']) if (!authored.radius?.[fixed]) out.push(`tokens.json: radius.${fixed} must stay in the authored tokens, outside every option`);
  for (const role of [...Object.keys(options.space.roles).map((r) => `space.${r}`), ...Object.keys(options.shape.roles).map((r) => `radius.${r}`)]) {
    const [g, k] = role.split('.');
    if (authored[g]?.[k]) out.push(`tokens.json: ${role} is a role the options own; remove it from tokens.json`);
  }
  const walk = (/** @type {any} */ g, /** @type {string[]} */ p) => {
    for (const [k, t] of Object.entries(g)) {
      if (k.startsWith('$') || !t || typeof t !== 'object') continue;
      if ('$value' in t) {
        if (t.$value === '{radius.full}' && !ROUND_BY_NATURE.has([...p, k].join('.'))) out.push(`${[...p, k].join('.')} reads radius.full: read radius.pill (square when sharp), or add it to ROUND_BY_NATURE if it's round by nature`);
      } else walk(t, [...p, k]);
    }
  };
  walk(authored, []);
  return out;
}

function main(/** @type {string[]} */ argv) {
  const config = read(CONFIG);
  const options = read(OPTIONS);
  const authored = read(join(SRC, 'tokens.json'));
  const found = problems(config, options, authored);
  const files = found.length ? {} : generate(config, options);
  const stale = [];
  for (const [name, tree] of Object.entries(files)) {
    const file = join(SRC, name);
    const text = serialise(tree);
    if (argv.includes('--check')) {
      if (!existsSync(file) || readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text) stale.push(`${relative(ROOT, file)} is stale: run npm run tokens`);
    } else writeFileSync(file, text);
  }
  for (const p of [...found, ...stale]) console.error(`✗ ${p}`);
  if (found.length || stale.length) return 1;
  console.log(`space and shape: ${argv.includes('--check') ? 'current' : 'wrote'}; theme ${config.space} + ${config.shape}; ${Object.keys(options.space.options).length} space and ${Object.keys(options.shape.options).length} shape options hold every invariant`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
